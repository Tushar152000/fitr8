/** The bowl when nothing matches (Figma "Icon/soup"). */
export const FALLBACK_FOOD_ICON: LucideIcon = Soup;

const escape = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const MATCHERS: [LucideIcon, RegExp][] = TABLE.map(([icon, words]) => [
  icon,
  new RegExp(`(^|[^a-z])(${words.map(escape).join("|")})`, "i"),
]);

/** "Masala oats" → Soup, "Black coffee" → Coffee, "Jeera rice" → Utensils, unknown → bowl. */
export function foodIcon(name: string): LucideIcon {
  return MATCHERS.find(([, re]) => re.test(name))?.[0] ?? FALLBACK_FOOD_ICON;
}
